export function motorcycleBrandNames(): readonly string[] {
  return Object.keys(MOTORCYCLE_MODELS).sort((a, b) => a.localeCompare(b));
}

export function motorcycleModelsForBrand(brand: string): readonly string[] {
  const normalizedBrand = brand.trim().toLowerCase();
  const entry = Object.entries(MOTORCYCLE_MODELS).find(
    ([name]) => name.toLowerCase() === normalizedBrand,
  );
  return entry?.[1] ?? [];
}
